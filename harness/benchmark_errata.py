"""Benchmark errata found by the all-wrong audit, for anyone who evaluates on these benchmarks: questions whose reference
answer is wrong or ambiguous (two blind raters, audit/adjudication_result.json), and MATH-500 / MATH-Hard questions whose
reference is written so that a grader without the MATH normalization marks every correct answer wrong
(audit/grader_resolved.json). Each question is identified by its row in the public Hugging Face test split.
Writes audit/benchmark_errata.md. Usage: python3 benchmark_errata.py (after canonical.py and grader_resolved.py)
"""
import os, json

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..")
SOURCE = {"math500": "HuggingFaceH4/MATH-500", "mathhard": "lighteval/MATH-Hard", "mmlupro": "TIGER-Lab/MMLU-Pro",
          "mmlu": "cais/mmlu (all)", "gsm8k": "openai/gsm8k (main)", "arc": "allenai/ai2_arc (ARC-Challenge)"}


def src(qid):
    name, row = qid.split(":")
    return f"`{SOURCE.get(name, name)}` test row {row}"


def question(S, qid, k=110):
    p = S[qid]["prompt"]
    for cut in ("Solve the problem. Show brief reasoning, then give the final answer in \\boxed{}.\n\n",
                "Solve the problem. Show brief reasoning, then write the final answer after '####'.\n\n", "Question: "):
        p = p.replace(cut, "")
    p = " ".join(p.split())
    p = (p[:k] + "…") if len(p) > k else p
    return p.replace("|", "\\|")


if __name__ == "__main__":
    S = json.load(open(os.path.join(ROOT, "runs", "items_snapshot.json")))
    adj = json.load(open(os.path.join(ROOT, "audit", "adjudication_result.json")))
    res = json.load(open(os.path.join(ROOT, "audit", "grader_resolved.json")))
    L = ["# Benchmark errata from the all-wrong audit", "",
         "Found while auditing every question that all models in *Combining LLMs Rarely Beats the Single Best Model* "
         "(arXiv:2606.27288) were graded wrong on. Generated by `harness/benchmark_errata.py`.", "",
         "## Wrong or ambiguous reference answers", "",
         "Two raters solved each question blind to the reference answer and to every model output "
         "(`audit/adjudication_result.json`; rule in `audit/ADJUDICATION_RULE.md`).", "",
         "| question | reference | raters' answers | verdict | question text |", "|---|---|---|---|---|"]
    for r in sorted(adj, key=lambda r: (r["class"], r["qid"])):
        if r["class"] in ("reference error", "ambiguous item"):
            L.append(f"| {src(r['qid'])} | {r['reference']} | {r['A']} / {r['B']} | {r['class']} | {question(S, r['qid'])} |")
    L += ["", "## Questions a naive math grader marks all-wrong", "",
          "Models answer these correctly, yet our first release's grader marked every model wrong on each of them: the "
          "reference is written with units, variable names, thousands separators, shorthand fractions or ±, or the answer "
          "has nested braces that a one-level `\\boxed{}` pattern cuts off. Use balanced-brace extraction and the MATH "
          "benchmark's answer normalization (`harness/grade.py`), or expect false all-wrong questions.", "",
          "| question | reference as written | answer the models give | why a naive grader fails |", "|---|---|---|---|"]
    seen = set()
    for r in res:
        if r["qid"].startswith(("math500", "mathhard")) and r["qid"] not in seen:
            seen.add(r["qid"]); top = next(iter(r["answers_marked_correct"]), "")
            ref = r["reference"].replace("|", "\\|"); top = str(top).replace("|", "\\|")
            why = ("nested braces in `\\boxed{}`" if " ".join(ref.split()) == " ".join(top.split()) else "reference format")
            L.append(f"| {src(r['qid'])} | `{ref}` | `{top}` | {why} |")
    out = os.path.join(ROOT, "audit", "benchmark_errata.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"[errata] wrote {out}: {sum(1 for r in adj if r['class'] in ('reference error', 'ambiguous item'))} wrong or ambiguous references, "
          f"{len(seen)} grader-breaking references")
